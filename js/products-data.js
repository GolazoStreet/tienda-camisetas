/** Devuelve un producto por su id, o undefined si no existe. */
function obtenerProductoPorId(id) {
  return PRODUCTOS.find((p) => p.id === id);
}

/** Devuelve el nombre legible de una liga a partir de su id. */
function nombreLiga(ligaId) {
  const liga = LIGAS.find((l) => l.id === ligaId);
  return liga ? liga.nombre : ligaId;
}

/** Si es false, no se muestra el nombre de la liga debajo de la foto del producto (el filtro de la izquierda sigue funcionando igual). */
function mostrarEtiquetaLiga(ligaId) {
  const liga = LIGAS.find((l) => l.id === ligaId);
  return !(liga && liga.ocultarEtiquetaProducto);
}

/**
 * Personalización (nombre y número) y parche solo están disponibles en las
 * camisetas de liga y en las de selecciones. Las de "retro" y "special" no
 * las ofrecen.
 */
const LIGAS_CON_PERSONALIZACION = ["espanola", "inglesa", "italiana", "alemana", "francesa", "selecciones"];
const LIGAS_CON_PARCHE_DE_LIGA = ["espanola", "inglesa", "italiana", "alemana", "francesa"];

/** Indica si un producto admite personalización (nombre y número) y parche. */
function permitePersonalizacion(producto) {
  return LIGAS_CON_PERSONALIZACION.includes(producto.liga);
}

/** Devuelve el tipo de parche disponible para un producto: "liga", "mundial" o null. */
function tipoParche(producto) {
  if (LIGAS_CON_PARCHE_DE_LIGA.includes(producto.liga)) return "liga";
  if (producto.liga === "selecciones") return "mundial";
  return null;
}

/** Texto a mostrar para el tipo de parche. */
function etiquetaParche(tipoParcheProducto) {
  if (tipoParcheProducto === "liga") return "Parche de la Liga";
  if (tipoParcheProducto === "mundial") return "Parche del Mundial";
  return "";
}

/**
 * Exporta el catálogo para poder usarlo también desde Node.js (por
 * ejemplo, la función serverless de netlify/functions/crear-sesion-stripe.js
 * necesita los precios REALES para calcular el total del pedido, en vez de
 * fiarse del importe que envíe el navegador del comprador).
 *
 * En el navegador, "module" no existe, así que este bloque no hace nada
 * ahí — el catálogo se sigue usando exactamente igual que siempre a
 * través de la variable global PRODUCTOS.
 */
if (typeof module !== "undefined" && module.exports) {
  module.exports = { PRODUCTOS, LIGAS };
}
